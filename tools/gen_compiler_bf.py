#!/usr/bin/env python3
import sys

# === Flat Helper Functions ===
S = " "
F = "\u3000"
def e(s): sys.stdout.write(s + "\n")
def R(n=1): 
    if n > 0: e((S + S + S) * n)
def L(n=1): 
    if n > 0: e((S + S + F) * n)
def I(n=1): 
    if n > 0: e((S + F + S) * n)
def D(n=1): 
    if n > 0: e((S + F + F) * n)
def O(): e(F + S + S)
def N(): e(F + S + F)
def B(): e(F + F + S)
def C(): e(F + F + F)
def Z(): B(); D(); C()

def emit_byte_to_buffer(val):
    Z()
    I(val)
    R(1)

def emit_bytes(vals):
    for v in vals:
        emit_byte_to_buffer(v)

