import sys

# Stage 7 (Windows): PE Binary Generator (Proof of Concept)
# Generates a Spaces program that outputs a minimal x86_64 PE (.exe) binary.
# The output binary allows Windows to recognize it as a valid executable.

def main():
    bf = []
    
    # Helper: emit byte
    def emit_byte(val):
        if val == 0:
            bf.append('.')
        else:
            bf.append('+' * val)
            bf.append('.')
            bf.append('[-]')

    # Minimal PE32+ (64-bit) Header Structure
    # This relies on strict alignment tricks to keep it small (~268 bytes).
    # It simply returns 42 (exit code).
    
    pe_bytes = [
        # --- MS-DOS Header ---
        0x4D, 0x5A, # 'MZ'
        0x90, 0x00, 0x03, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00,
        0xB8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 
        0x40, 0x00, 0x00, 0x00, # Pointer to PE Header (0x40)

        # --- PE Header (Starts at 0x40) ---
        0x50, 0x45, 0x00, 0x00, # 'PE\0\0'
        0x64, 0x86, # Machine (x64)
        0x01, 0x00, # Number of Sections (1)
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, # TimeDateStamp, PtrSymbolTable
        0x00, 0x00, 0x00, 0x00, # NumberOfSymbols
        0xF0, 0x00, # SizeOfOptionalHeader
        0x2E, 0x00, # Characteristics (Executable | Large Address Aware)

        # --- Optional Header (Standard) ---
        0x0B, 0x02, # Magic (PE32+)
        0x02, 0x1E, # Linker Version
        0x00, 0x02, 0x00, 0x00, # SizeOfCode
        0x00, 0x02, 0x00, 0x00, # SizeOfInitializedData
        0x00, 0x00, 0x00, 0x00, # SizeOfUninitializedData
        0x00, 0x10, 0x00, 0x00, # AddressOfEntryPoint (Offset 0x1000)
        0x00, 0x10, 0x00, 0x00, # BaseOfCode

        # --- Optional Header (Windows) ---
        0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, # ImageBase (0x400000)
        0x04, 0x00, 0x00, 0x00, # SectionAlignment (4KB)
        0x00, 0x02, 0x00, 0x00, # FileAlignment (512 bytes)
        0x04, 0x00, 0x00, 0x00, # OS Version
        0x00, 0x00, 0x00, 0x00, # Image Version
        0x04, 0x00, 0x00, 0x00, # Subsystem Version
        0x00, 0x00, 0x00, 0x00, # Win32VersionValue
        0x00, 0x20, 0x00, 0x00, # SizeOfImage
        0x00, 0x02, 0x00, 0x00, # SizeOfHeaders
        0x00, 0x00, 0x00, 0x00, # CheckSum
        0x03, 0x00, # Subsystem (Console)
        0x00, 0x00, # DllCharacteristics
        0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, # SizeOfStackReserve
        0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, # SizeOfStackCommit
        0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, # SizeOfHeapReserve
        0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, # SizeOfHeapCommit
        0x00, 0x00, 0x00, 0x00, # LoaderFlags
        0x10, 0x00, 0x00, 0x00, # NumberOfRvaAndSizes

        # --- Data Directories (All 0 for minimal) ---
        # 16 entries * 8 bytes = 128 bytes of Zeros
    ]
    
    # Fill Data Directories with 0
    pe_bytes.extend([0] * 128)

    # --- Section Table (.text) ---
    section_bytes = [
        0x2E, 0x74, 0x65, 0x78, 0x74, 0x00, 0x00, 0x00, # Name ".text"
        0x06, 0x00, 0x00, 0x00, # VirtualSize
        0x00, 0x10, 0x00, 0x00, # VirtualAddress (RVA 0x1000)
        0x06, 0x00, 0x00, 0x00, # SizeOfRawData (6 bytes)
        0x00, 0x02, 0x00, 0x00, # PointerToRawData (Offset 512)
        0x00, 0x00, 0x00, 0x00, # PtrReloc
        0x00, 0x00, 0x00, 0x00, # PtrLineNum
        0x00, 0x00, # RelocNum
        0x00, 0x00, # LineNum
        0x20, 0x00, 0x00, 0x60  # Characteristics (Code | Execute | Read)
    ]
    pe_bytes.extend(section_bytes)

    # Padding to 512 bytes (FileAlignment)
    # Current size check
    current_len = len(pe_bytes)
    padding_len = 512 - current_len
    pe_bytes.extend([0] * padding_len)

    # --- Machine Code (At Offset 512 / RVA 0x1000) ---
    # mov eax, 42 (0x2A)
    # ret
    code_bytes = [0xB8, 0x2A, 0x00, 0x00, 0x00, 0xC3]
    pe_bytes.extend(code_bytes)

    # Emit Loop
    for b in pe_bytes:
        emit_byte(b)

    # Convert to Spaces
    S, F = " ", "\u3000"
    mapping = {'>':S*3, '<':S*2+F, '+':S+F+S, '-':S+F+F, '.':F+S+S, ',':F+S+F, '[':F*2+S, ']':F*3}
    
    full_bf = "".join(bf)
    print("".join([mapping.get(c, '') for c in full_bf]), end='')

if __name__ == "__main__":
    main()
