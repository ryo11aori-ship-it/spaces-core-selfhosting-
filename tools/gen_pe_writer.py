import sys

# Stage 7 (Windows): PE Binary Generator (Proof of Concept)
# Generates a Spaces program that outputs a minimal x86_64 PE (.exe) binary.

def main():
    bf = []
    
    def emit_byte(val):
        if val == 0:
            bf.append('.')
        else:
            bf.append('+' * val)
            bf.append('.')
            bf.append('[-]')

    # Minimal PE32+ (64-bit) Header returning 42
    # Structure aligned to 512 bytes
    
    pe_bytes = [
        # --- MS-DOS Header ---
        0x4D, 0x5A, # 'MZ'
        0x90, 0x00, 0x03, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00,
        0xB8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 
        0x40, 0x00, 0x00, 0x00, # Pointer to PE Header

        # --- PE Header ---
        0x50, 0x45, 0x00, 0x00, # 'PE\0\0'
        0x64, 0x86, # Machine (x64)
        0x01, 0x00, # Number of Sections (1)
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0xF0, 0x00, # SizeOfOptionalHeader
        0x2E, 0x00, # Characteristics

        # --- Optional Header ---
        0x0B, 0x02, # Magic (PE32+)
        0x02, 0x1E,
        0x00, 0x02, 0x00, 0x00,
        0x00, 0x02, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x10, 0x00, 0x00, # AddressOfEntryPoint (RVA 0x1000)
        0x00, 0x10, 0x00, 0x00, # BaseOfCode

        # --- Windows Specific ---
        0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, # ImageBase
        0x04, 0x00, 0x00, 0x00, # SectionAlignment
        0x00, 0x02, 0x00, 0x00, # FileAlignment
        0x04, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x04, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x20, 0x00, 0x00, # SizeOfImage
        0x00, 0x02, 0x00, 0x00, # SizeOfHeaders
        0x00, 0x00, 0x00, 0x00,
        0x03, 0x00, # Subsystem (Console)
        0x00, 0x00,
        0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x10, 0x00, 0x00, 0x00,

        # --- Data Directories (Zero) ---
    ]
    pe_bytes.extend([0] * 128)

    # --- Section Table (.text) ---
    section_bytes = [
        0x2E, 0x74, 0x65, 0x78, 0x74, 0x00, 0x00, 0x00,
        0x06, 0x00, 0x00, 0x00, # VirtualSize
        0x00, 0x10, 0x00, 0x00, # VirtualAddress (0x1000)
        0x06, 0x00, 0x00, 0x00, # RawSize
        0x00, 0x02, 0x00, 0x00, # RawPtr (512)
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00,
        0x00, 0x00,
        0x20, 0x00, 0x00, 0x60  # Execute | Read | Code
    ]
    pe_bytes.extend(section_bytes)

    # Padding to 512 bytes
    current_len = len(pe_bytes)
    pe_bytes.extend([0] * (512 - current_len))

    # --- Machine Code (RVA 0x1000 / Offset 512) ---
    # mov eax, 42; ret
    code_bytes = [0xB8, 0x2A, 0x00, 0x00, 0x00, 0xC3]
    pe_bytes.extend(code_bytes)

    # Emit
    for b in pe_bytes:
        emit_byte(b)

    # Convert to Spaces
    S, F = " ", "\u3000"
    mapping = {'>':S*3, '<':S*2+F, '+':S+F+S, '-':S+F+F, '.':F+S+S, ',':F+S+F, '[':F*2+S, ']':F*3}
    full_bf = "".join(bf)
    
    # FIX: Use binary stdout to write UTF-8 directly, avoiding Windows CP1252 issues
    output_str = "".join([mapping.get(c, '') for c in full_bf])
    sys.stdout.buffer.write(output_str.encode('utf-8'))

if __name__ == "__main__":
    main()
